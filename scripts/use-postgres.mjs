// Production uses Postgres (Vercel functions have no persistent disk); local dev and
// tests keep SQLite. This writes prisma/schema.postgres.prisma from the main schema
// so both always have the same models.
import { readFileSync, writeFileSync } from "node:fs";

const url = process.env.DATABASE_URL ?? "";
if (!/^postgres(ql)?:\/\//.test(url)) {
  console.error(
    "\nBursar needs a Postgres database in production, and DATABASE_URL is not a postgres:// URL.\n" +
      "On Vercel: open the project, Storage tab, Create Database, Neon (Postgres), connect it to this project, then redeploy.\n",
  );
  process.exit(1);
}

const src = readFileSync("prisma/schema.prisma", "utf8");
const direct = process.env.DATABASE_URL_UNPOOLED ? "DATABASE_URL_UNPOOLED" : process.env.DIRECT_DATABASE_URL ? "DIRECT_DATABASE_URL" : null;
const datasource = `datasource db {
  provider  = "postgresql"
  url       = env("DATABASE_URL")${direct ? `\n  directUrl = env("${direct}")` : ""}
}`;
const out = src.replace(/datasource db \{[\s\S]*?\n\}/, datasource);
if (out === src) throw new Error("Could not find the datasource block in prisma/schema.prisma");
writeFileSync("prisma/schema.postgres.prisma", `// Generated by scripts/use-postgres.mjs. Do not edit; edit schema.prisma.\n${out}`);
console.log(`Wrote prisma/schema.postgres.prisma${direct ? ` (direct URL: ${direct})` : ""}`);
